// Real-browser acceptance for drawing management. Run after npm run build.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require('playwright-core');
const out=path.join(__dirname,'../qa/ui-refine');
(async()=>{
 fs.mkdirSync(out,{recursive:true});
 const browser=await chromium.launch({headless:true,...(process.env.STUDIO_BROWSER?{executablePath:process.env.STUDIO_BROWSER}:{channel:'chrome'})});
 const errors=[],network=[];
 try{
  const context=await browser.newContext({viewport:{width:1440,height:1000},colorScheme:'light',acceptDownloads:true}),page=await context.newPage();
  page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
  page.on('request',r=>{if(/^https?:/.test(r.url()))network.push(r.url())});
  await page.addInitScript(()=>{window.showSaveFilePicker=undefined});
  await page.goto(pathToFileURL(path.join(__dirname,'../dist/index.html')).href);
  const duplicate=page.locator('[data-action="duplicate-document"]'),remove=page.locator('[data-action="delete-document"]');
  assert.equal(await page.locator('[data-action="rename-document"],#rename-dialog').count(),0,'dedicated rename UI is removed');
  const state=()=>page.evaluate(()=>({document:JSON.stringify(SpatialEditor.document),undo:SpatialEditor.undoCount}));
  const name=()=>page.evaluate(()=>SpatialEditor.document.name);
  const remaining=()=>page.evaluate(()=>{const {name,...rest}=SpatialEditor.document;return JSON.stringify(rest)});
  const drawingNumber=async expected=>assert.equal(await page.locator('#shell-view-index').textContent(),expected,'header shows the active drawing position in the project');
  await drawingNumber('00');
  assert(await duplicate.isDisabled()&&await remove.isDisabled(),'drawing actions are disabled without a drawing');
  assert.equal(await page.locator('.drawing-heading-actions [data-action="new"]').count(),1,'new is in the engineering drawing section');
  await page.locator('[data-action="new"]').click();await page.locator('#new-name').fill('入口空间');await page.locator('#new-dialog [data-template="space"]').click();
  assert.equal(await name(),'入口空间');assert.equal(await page.locator('#document-count').textContent(),'1');
  await drawingNumber('01');
  const original=await state(),geometry=await remaining();
  await page.locator('[data-panel="document"]').click();
  const input=()=>page.locator('#doc-name');
  await input().fill('中庭 <入口>');await input().press('Tab');
  assert.equal(await name(),'中庭 <入口>');assert.equal(await page.evaluate(()=>SpatialEditor.undoCount),original.undo+1,'one field edit is one history entry');
  assert.equal(await remaining(),geometry,'document settings preserve all artwork');
  assert.equal(await page.locator('#doc-title').textContent(),'中庭 <入口>');assert.equal(await page.locator('#document-select option:checked').textContent(),'中庭 <入口>');
  await page.locator('[data-action="undo"]').click();assert.equal(await name(),'入口空间');assert.equal(await remaining(),geometry);
  await page.locator('[data-action="redo"]').click();assert.equal(await name(),'中庭 <入口>');
  await duplicate.click();assert.equal(await name(),'中庭 <入口> 副本');assert.equal(await page.locator('#document-count').textContent(),'2');
  await drawingNumber('02');
  const duplicateState=await state();
  for(const mode of ['solid','elevation','plan']){await page.locator(`[data-view="${mode}"]`).click();await drawingNumber('02')}
  assert.deepEqual(await state(),duplicateState,'view changes preserve the drawing and history');
  await remove.click();assert.equal(await name(),'中庭 <入口>');assert.equal(await page.locator('#document-count').textContent(),'1');
  await drawingNumber('01');
  await page.locator('[data-action="undo"]').click();assert.equal(await page.locator('#document-count').textContent(),'2');
  await page.locator('[data-action="redo"]').click();assert.equal(await page.locator('#document-count').textContent(),'1');
  // Verify the actual JSON download and UI file import, not only serialization helpers.
  const downloadEvent=page.waitForEvent('download');await page.locator('[data-action="project"]').click();const download=await downloadEvent;
  const jsonPath=path.join(out,'renamed-project.json');await download.saveAs(jsonPath);const json=JSON.parse(fs.readFileSync(jsonPath,'utf8'));
  assert.equal(json.documents[0].name,'中庭 <入口>');assert.deepEqual(json.documents[0].objects,JSON.parse(geometry).objects);
  await page.locator('[data-action="new"]').click();await page.locator('#new-name').fill('体验曲线');await page.locator('#new-dialog [data-template="curve"]').click();
  await drawingNumber('02');
  const chart=await page.evaluate(()=>JSON.stringify(SpatialEditor.document.curve));
  await duplicate.click();assert.equal(await name(),'体验曲线 副本');assert.equal(await page.evaluate(()=>JSON.stringify(SpatialEditor.document.curve)),chart);
  await drawingNumber('03');
  await remove.click();assert.equal(await name(),'中庭 <入口>');
  await drawingNumber('01');
  await remove.click();assert.equal(await name(),'体验曲线');await drawingNumber('01');
  await page.locator('[data-action="undo"]').click();assert.equal(await name(),'体验曲线');await drawingNumber('02');
  await page.locator('[data-action="redo"]').click();await drawingNumber('01');
  const chooserEvent=page.waitForEvent('filechooser');await page.locator('[data-action="import"]').click();await (await chooserEvent).setFiles(jsonPath);await page.waitForFunction(()=>SpatialEditor.project.documents.length===1&&SpatialEditor.document.name==='中庭 <入口>');
  assert.equal(await remaining(),geometry,'JSON import preserves the renamed drawing and artwork');
  await drawingNumber('01');
  // The two remaining management actions stay aligned and usable on a narrow screen.
  await page.setViewportSize({width:360,height:844});await page.locator('[data-shell-pane="tools"]').click();
  assert.equal(await page.locator('.sub-actions button').count(),2);
  const left=await duplicate.boundingBox(),right=await remove.boundingBox();
  assert(Math.abs(left.y-right.y)<1&&Math.abs(left.width-right.width)<1&&right.x+right.width<=360,'management actions use two equal columns within the screen');
  await duplicate.click();assert.equal(await name(),'中庭 <入口> 副本');await remove.click();assert.equal(await name(),'中庭 <入口>');
  await drawingNumber('01');
  await page.locator('[data-shell-pane="properties"]').click();await page.locator('[data-panel="document"]').click();
  await input().fill('手机端图稿');await input().press('Tab');assert.equal(await name(),'手机端图稿');
  await page.locator('[data-shell-pane="tools"]').click();
  await page.locator('[data-action="new"]').click();await page.locator('#new-name').fill('移动端新增');await page.locator('#new-dialog [data-template="curve"]').click();
  assert.equal(await name(),'移动端新增');assert.equal(await page.locator('[data-shell-pane="canvas"]').getAttribute('aria-pressed'),'true');
  await drawingNumber('02');
  await page.reload();assert.deepEqual(await page.evaluate(()=>SpatialEditor.project.documents.map(d=>d.name)),['手机端图稿','移动端新增'],'autosave restores drawing names');
  await drawingNumber('02');
  await page.locator('[data-shell-pane="tools"]').click();await page.waitForTimeout(220);await page.screenshot({path:path.join(out,'drawings-mobile.png')});
  assert.deepEqual(errors,[],'no browser/CSP errors');assert.deepEqual(network,[],'no online resources');
  fs.writeFileSync(path.join(out,'document-management.json'),JSON.stringify({pass:true,checks:['rename button and dialog removed','local new','document settings name edit','duplicate/delete and undo/redo','artwork isolation','drawing number across views, deletion, undo/redo, import and reload','curve duplication','actual JSON download/import','phone two-column management','autosave reload'],browserErrors:errors,onlineRequests:network},null,2));
  console.log('PASS Chrome drawing management: rename button/dialog removed; local new; document settings name edit; duplicate/delete and undo/redo; drawing number across views/deletion/import/reload; artwork/curve preservation; JSON download/import; phone two-column actions and autosave. Evidence: qa/ui-refine/.');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
